def load_image(path):
    img = cv2.imread(path, cv2.IMREAD_COLOR)           # BGR, uint8
    if img is None:
        raise FileNotFoundError(f"Could not read image: {path}")
    return cv2.cvtColor(img, cv2.COLOR_BGR2RGB).astype(np.float64)


def rgb_to_gray(img):
    if img.ndim == 2:
        return img
    gray = cv2.cvtColor(img.astype(np.float32), cv2.COLOR_RGB2GRAY)
    return gray.astype(np.float64)


def to_uint8(img):
    return np.clip(np.round(img), 0, 255).astype(np.uint8)


def resize_nearest(img, new_h, new_w):
    """Nearest-neighbour resize, from scratch (so both hybrid inputs match)."""
    h, w = img.shape[:2]
    rows = (np.arange(new_h) * h / new_h).astype(int)
    cols = (np.arange(new_w) * w / new_w).astype(int)
    return img[rows][:, cols]

def compute_histogram(gray_u8, levels=256):
    hist = np.zeros(levels, dtype=np.int64)
    # count how many pixels have each intensity
    for v in gray_u8.ravel():
        hist[v] += 1
    return hist


def equalize_gray(gray, levels=256):
    """
    Classic histogram equalization:
        pdf(k) = hist(k) / N
        cdf(k) = sum_{j<=k} pdf(j)
        s_k    = round( (cdf(k) - cdf_min) / (1 - cdf_min) * (L-1) )
    """
    g = to_uint8(gray)
    hist = compute_histogram(g, levels)
    n = g.size
    pdf = hist / n
    cdf = np.cumsum(pdf)
    cdf_min = cdf[hist > 0].min()              # first non-empty bin
    mapping = np.round((cdf - cdf_min) / (1.0 - cdf_min + 1e-12) * (levels - 1))
    mapping = np.clip(mapping, 0, levels - 1).astype(np.uint8)
    return mapping[g], hist, cdf, mapping


def rgb_to_ycbcr(img):
    r, g, b = img[..., 0], img[..., 1], img[..., 2]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = 128 - 0.168736 * r - 0.331264 * g + 0.5 * b
    cr = 128 + 0.5 * r - 0.418688 * g - 0.081312 * b
    return y, cb, cr


def ycbcr_to_rgb(y, cb, cr):
    r = y + 1.402 * (cr - 128)
    g = y - 0.344136 * (cb - 128) - 0.714136 * (cr - 128)
    b = y + 1.772 * (cb - 128)
    return np.stack([r, g, b], axis=-1)


def equalize_color(img):
    """Equalize only the luminance (Y) so colours are not distorted."""
    y, cb, cr = rgb_to_ycbcr(img)
    y_eq, *_ = equalize_gray(y)
    return to_uint8(ycbcr_to_rgb(y_eq.astype(np.float64), cb, cr))


def img_equalization_histogram(img):
    gray = rgb_to_gray(img)
    eq, hist, cdf, _ = equalize_gray(gray)
    _, hist_eq, cdf_eq, _ = equalize_gray(eq)  # histogram after equalization

    fig, ax = plt.subplots(2, 3, figsize=(14, 7))
